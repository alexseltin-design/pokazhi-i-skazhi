"""Build helper for «Покажи и скажи».

    python3 tools/build.py

1. Rewrites sw.js with the current list of files and a new cache version,
   so phones and tablets pick up the update.
2. Makes dist/pokazhi-i-skazhi.html: the whole game in ONE file
   (styles, scripts and pictures inside) for quick previews or sharing.
"""
import json,os,re,base64,time
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
order=json.load(open('tools/script-order.json'))
files=['./','index.html','manifest.webmanifest','css/style.css']+order
for d in ('assets/img','assets/icons','assets/audio'):
    for f in sorted(os.listdir(d)):
        if not f.startswith('.') and not f.endswith('.json'): files.append(f'{d}/{f}')
version=time.strftime('%Y%m%d-%H%M%S')
sw=f"""/* Offline cache. Generated by tools/build.py — do not edit by hand. */
const CACHE='pokazhi-{version}';
const FILES={json.dumps(files,indent=0)};
self.addEventListener('install',e=>{{e.waitUntil(caches.open(CACHE).then(c=>c.addAll(FILES)));self.skipWaiting();}});
self.addEventListener('activate',e=>{{e.waitUntil(caches.keys().then(ks=>Promise.all(ks.filter(k=>k!==CACHE).map(k=>caches.delete(k)))));self.clients.claim();}});
self.addEventListener('fetch',e=>{{
  if(e.request.method!=='GET')return;
  if(e.request.mode==='navigate'){{
    e.respondWith(fetch(e.request).then(r=>{{const cp=r.clone();caches.open(CACHE).then(c=>c.put('./index.html',cp));return r;}}).catch(()=>caches.match('./index.html')));
    return;
  }}
  e.respondWith(caches.match(e.request).then(hit=>hit||fetch(e.request).then(r=>{{
    if(r.ok||r.type==='opaque'){{const cp=r.clone();caches.open(CACHE).then(c=>c.put(e.request,cp));}}
    return r;
  }})));
}});
"""
open('sw.js','w',encoding='utf-8').write(sw)
# ---- single-file bundle
html=open('index.html',encoding='utf-8').read()
css=open('css/style.css',encoding='utf-8').read()
html=html.replace('<link rel="stylesheet" href="css/style.css">',f'<style>\n{css}</style>')
def datauri(path):
    ext=path.rsplit('.',1)[1];mime={'webp':'image/webp','png':'image/png','svg':'image/svg+xml'}[ext]
    return f'data:{mime};base64,'+base64.b64encode(open(path,'rb').read()).decode()
scripts=[]
for f in order:
    src=open(f,encoding='utf-8').read()
    if f=='js/images.js':
        src=re.sub(r'"(assets/img/[^"]+)"',lambda m:'"'+datauri(m.group(1))+'"',src)
    scripts.append(f'/* ===== {f} ===== */\n'+src)
bundle='<script>\n'+'\n'.join(scripts)+'</script>\n'
html=re.sub(r'<!-- scripts run in this order.*?-->\n(<script src="[^"]+"></script>\n)+',lambda m:bundle,html,flags=re.S)
html=re.sub(r'<script>\n/\* offline support.*?</script>\n','',html,flags=re.S)
html=html.replace('<link rel="manifest" href="manifest.webmanifest">\n','').replace('<link rel="apple-touch-icon" href="assets/icons/icon-180.png">\n','').replace('<link rel="icon" href="assets/icons/icon-180.png">\n','')
os.makedirs('dist',exist_ok=True)
open('dist/pokazhi-i-skazhi.html','w',encoding='utf-8').write(html)
print('sw.js:',len(files),'files, cache',version)
print('dist/pokazhi-i-skazhi.html:',len(html)//1024,'KB')

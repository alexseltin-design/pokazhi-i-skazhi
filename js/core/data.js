/* "bag" randomness: every task comes up once, in random order, before anything repeats */
const BAGS={};
function bagNext(key,n){
  let b=BAGS[key];
  if(!b||b.n!==n||!b.list.length){
    const l=shuffle([...Array(n).keys()]),last=b?b.last:undefined;
    if(l.length>1&&l[l.length-1]===last){const t=l[0];l[0]=l[l.length-1];l[l.length-1]=t;}
    b=BAGS[key]={n,list:l,last};
  }
  const v=b.list.pop();b.last=v;return v;
}
